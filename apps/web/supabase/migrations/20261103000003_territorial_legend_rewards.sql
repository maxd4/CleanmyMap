-- BOUNDED PRE-APPLICATION REPAIR: this migration was published but is absent
-- from the linked migration history. The repair only makes its table
-- definitions executable; the RPC contract correction is forward-only in
-- 20261103000004_territorial_legend_rewards_contract.sql.
-- PURPOSE: Persist only territorial legend hold periods and award proofs, then
--          reconcile them into the existing progression_events BADGE_ONLY ledger.
-- CALLER: server-side daily/event reconciliation with service_role only.
-- AUTHORIZATION_BOUNDARY: clients cannot read or write either private table or RPC.
-- IDEMPOTENCY: stable proof_id and unique holder-period/award identities.
-- ATOMICITY: one snapshot closes interruptions, advances periods and inserts proofs.
-- FAILURE_BEHAVIOR: advisory lock serializes snapshots; unique conflicts are safe.
-- SEARCH_PATH: fixed for SECURITY DEFINER.
-- GRANTS: service_role only.

create table if not exists public.territorial_legend_hold_periods (
  id bigint generated by default as identity primary key,
  user_id text not null,
  level text not null check (level in ('arrondissement', 'commune', 'department', 'region', 'country')),
  territory_code text not null,
  territory_label text not null,
  started_on date not null,
  last_verified_on date not null,
  ended_on date,
  validity_status text not null default 'active' check (validity_status in ('active', 'closed', 'invalidated')),
  source_fingerprint text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (last_verified_on >= started_on),
  check (ended_on is null or ended_on >= started_on),
  check ((validity_status = 'active' and ended_on is null) or validity_status <> 'active')
);

create unique index if not exists territorial_legend_hold_period_identity
  on public.territorial_legend_hold_periods(user_id, level, territory_code, started_on);

create unique index if not exists territorial_legend_one_open_period
  on public.territorial_legend_hold_periods(user_id, level, territory_code)
  where validity_status = 'active';

create index if not exists territorial_legend_hold_periods_user_idx
  on public.territorial_legend_hold_periods(user_id, updated_at desc);

create table if not exists public.territorial_legend_award_proofs (
  proof_id text primary key,
  user_id text not null,
  level text not null check (level in ('arrondissement', 'commune', 'department', 'region', 'country')),
  territory_code text not null,
  award_kind text not null check (award_kind in ('conquest', 'longevity')),
  threshold_days integer not null check (threshold_days >= 0),
  hold_period_id bigint not null references public.territorial_legend_hold_periods(id),
  hold_started_on date not null,
  held_through_on date not null,
  awarded_on date not null,
  valid_from date not null,
  valid_until date,
  validity_status text not null default 'active' check (validity_status in ('active', 'invalidated')),
  source_fingerprint text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((award_kind = 'conquest' and threshold_days = 0) or (award_kind = 'longevity' and threshold_days in (7, 30, 90, 180, 365, 730))),
  check (held_through_on >= hold_started_on),
  check (valid_until is null or valid_until >= valid_from)
);

create unique index if not exists territorial_legend_award_identity
  on public.territorial_legend_award_proofs(user_id, level, territory_code, award_kind, threshold_days);

create index if not exists territorial_legend_award_proofs_user_idx
  on public.territorial_legend_award_proofs(user_id, validity_status, awarded_on desc);

alter table public.territorial_legend_hold_periods enable row level security;
alter table public.territorial_legend_award_proofs enable row level security;

drop policy if exists territorial_legend_hold_periods_service_only on public.territorial_legend_hold_periods;
create policy territorial_legend_hold_periods_service_only on public.territorial_legend_hold_periods
for all using (auth.role() = 'service_role') with check (auth.role() = 'service_role');

drop policy if exists territorial_legend_award_proofs_service_only on public.territorial_legend_award_proofs;
create policy territorial_legend_award_proofs_service_only on public.territorial_legend_award_proofs
for all using (auth.role() = 'service_role') with check (auth.role() = 'service_role');

revoke all on public.territorial_legend_hold_periods from public, anon, authenticated;
revoke all on public.territorial_legend_award_proofs from public, anon, authenticated;
grant select, insert, update on public.territorial_legend_hold_periods to service_role;
grant select, insert, update on public.territorial_legend_award_proofs to service_role;
grant usage, select on sequence public.territorial_legend_hold_periods_id_seq to service_role;

create or replace function public.reconcile_territorial_legend_snapshot(
  p_effective_on date,
  p_winners jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_winner record;
  v_hold record;
  v_period_id bigint;
  v_started_on date;
  v_last_verified_on date;
  v_days integer;
  v_threshold integer;
  v_affected_users text[] := '{}';
  v_closed_users text[] := '{}';
  v_inserted_proofs integer := 0;
  v_row_count integer := 0;
  v_extended_periods integer := 0;
  v_closed_periods integer := 0;
begin
  if coalesce(current_setting('request.jwt.claim.role', true), '') <> 'service_role' then
    raise exception 'service_role required';
  end if;
  if p_effective_on is null or p_effective_on > (now() at time zone 'Europe/Paris')::date then
    raise exception 'effective date must be a non-future civil date';
  end if;

  -- One global daily snapshot prevents two event handlers from inventing a
  -- second continuous day for the same territorial title.
  perform pg_advisory_xact_lock(hashtextextended('territorial-legends:global', 0));
  perform pg_advisory_xact_lock(hashtextextended('territorial-legends:' || p_effective_on::text, 0));

  select coalesce(array_agg(distinct h.user_id), '{}')
    into v_closed_users
    from public.territorial_legend_hold_periods h
   where h.validity_status = 'active'
     and not exists (
       select 1
         from jsonb_array_elements(coalesce(p_winners, '[]'::jsonb)) item
        where item ->> 'userId' = h.user_id
          and item ->> 'level' = h.level
          and item ->> 'territoryCode' = h.territory_code
     );

  update public.territorial_legend_hold_periods h
     set ended_on = h.last_verified_on,
         validity_status = 'closed',
         updated_at = clock_timestamp()
   where h.validity_status = 'active'
     and not exists (
       select 1
         from jsonb_array_elements(coalesce(p_winners, '[]'::jsonb)) item
        where item ->> 'userId' = h.user_id
          and item ->> 'level' = h.level
          and item ->> 'territoryCode' = h.territory_code
     );
  get diagnostics v_closed_periods = row_count;
  v_affected_users := v_closed_users;

  for v_winner in
    select * from jsonb_to_recordset(coalesce(p_winners, '[]'::jsonb)) as winner(
      user_id text,
      level text,
      territory_code text,
      territory_label text,
      effective_on date,
      score integer,
      rank integer,
      tie_size integer,
      source_fingerprint text
    )
  loop
    if v_winner.effective_on is distinct from p_effective_on or v_winner.rank <> 1 or v_winner.score < 2 or v_winner.tie_size < 1 then
      raise exception 'invalid territorial winner snapshot';
    end if;
    if not (v_winner.user_id = any(v_affected_users)) then
      v_affected_users := array_append(v_affected_users, v_winner.user_id);
    end if;

    select h.*
      into v_hold
      from public.territorial_legend_hold_periods h
     where h.user_id = v_winner.user_id
       and h.level = v_winner.level
       and h.territory_code = v_winner.territory_code
       and h.validity_status = 'active'
     for update;

    if not found then
      insert into public.territorial_legend_hold_periods (
        user_id, level, territory_code, territory_label, started_on,
        last_verified_on, validity_status, source_fingerprint, updated_at
      ) values (
        v_winner.user_id, v_winner.level, v_winner.territory_code,
        v_winner.territory_label, p_effective_on, p_effective_on, 'active',
        v_winner.source_fingerprint, clock_timestamp()
      ) returning id, started_on, last_verified_on into v_period_id, v_started_on, v_last_verified_on;
    elsif v_hold.last_verified_on = p_effective_on - 1 or v_hold.last_verified_on = p_effective_on then
      update public.territorial_legend_hold_periods
         set last_verified_on = greatest(last_verified_on, p_effective_on),
             territory_label = v_winner.territory_label,
             source_fingerprint = v_winner.source_fingerprint,
             updated_at = clock_timestamp()
       where id = v_hold.id;
      v_period_id := v_hold.id;
      v_started_on := v_hold.started_on;
      v_last_verified_on := greatest(v_hold.last_verified_on, p_effective_on);
      v_extended_periods := v_extended_periods + 1;
    else
      update public.territorial_legend_hold_periods
         set ended_on = last_verified_on,
             validity_status = 'closed',
             updated_at = clock_timestamp()
       where id = v_hold.id;
      v_closed_periods := v_closed_periods + 1;
      insert into public.territorial_legend_hold_periods (
        user_id, level, territory_code, territory_label, started_on,
        last_verified_on, validity_status, source_fingerprint, updated_at
      ) values (
        v_winner.user_id, v_winner.level, v_winner.territory_code,
        v_winner.territory_label, p_effective_on, p_effective_on, 'active',
        v_winner.source_fingerprint, clock_timestamp()
      ) returning id, started_on, last_verified_on into v_period_id, v_started_on, v_last_verified_on;
    end if;

    -- A proof remains historical and auditable; this uniqueness boundary means
    -- a reconquest never duplicates an already acquired threshold.
    insert into public.territorial_legend_award_proofs (
      proof_id, user_id, level, territory_code, award_kind, threshold_days,
      hold_period_id, hold_started_on, held_through_on, awarded_on,
      valid_from, validity_status, source_fingerprint
    ) values (
      v_winner.user_id || ':' || v_winner.level || ':' || v_winner.territory_code || ':conquest:0',
      v_winner.user_id, v_winner.level, v_winner.territory_code, 'conquest', 0,
      v_period_id, v_started_on, v_last_verified_on, p_effective_on,
      p_effective_on, 'active', v_winner.source_fingerprint
    ) on conflict (user_id, level, territory_code, award_kind, threshold_days) do nothing;
    get diagnostics v_row_count = row_count;
    v_inserted_proofs := v_inserted_proofs + v_row_count;

    v_days := v_last_verified_on - v_started_on + 1;
    foreach v_threshold in array array[7, 30, 90, 180, 365, 730] loop
      if v_days >= v_threshold then
        insert into public.territorial_legend_award_proofs (
          proof_id, user_id, level, territory_code, award_kind, threshold_days,
          hold_period_id, hold_started_on, held_through_on, awarded_on,
          valid_from, validity_status, source_fingerprint
        ) values (
          v_winner.user_id || ':' || v_winner.level || ':' || v_winner.territory_code || ':longevity:' || v_threshold,
          v_winner.user_id, v_winner.level, v_winner.territory_code, 'longevity', v_threshold,
          v_period_id, v_started_on, v_last_verified_on, p_effective_on,
          p_effective_on, 'active', v_winner.source_fingerprint
        ) on conflict (user_id, level, territory_code, award_kind, threshold_days) do nothing;
        get diagnostics v_row_count = row_count;
        v_inserted_proofs := v_inserted_proofs + v_row_count;
      end if;
    end loop;
  end loop;

  return jsonb_build_object(
    'status', 'applied',
    'affectedUserIds', to_jsonb(v_affected_users),
    'insertedProofs', v_inserted_proofs,
    'extendedPeriods', v_extended_periods,
    'closedPeriods', v_closed_periods
  );
end;
$$;

revoke all on function public.reconcile_territorial_legend_snapshot(date, jsonb) from public, anon, authenticated;
grant execute on function public.reconcile_territorial_legend_snapshot(date, jsonb) to service_role;

create or replace function public.invalidate_territorial_legend_history(
  p_hold_period_ids bigint[],
  p_proof_ids text[],
  p_invalidated_on date
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_hold_period_ids bigint[] := coalesce(p_hold_period_ids, '{}'::bigint[]);
  v_proof_ids text[] := coalesce(p_proof_ids, '{}'::text[]);
  v_hold_count integer := 0;
  v_proof_count integer := 0;
  v_affected_users text[] := '{}';
begin
  if coalesce(current_setting('request.jwt.claim.role', true), '') <> 'service_role' then
    raise exception 'service_role required';
  end if;
  if p_invalidated_on is null or p_invalidated_on > (now() at time zone 'Europe/Paris')::date then
    raise exception 'invalidated date must be a non-future civil date';
  end if;

  -- A correction cannot race a daily snapshot or another correction. It never
  -- deletes rows and never fills a period beyond its last verified day.
  perform pg_advisory_xact_lock(hashtextextended('territorial-legends:global', 0));
  perform pg_advisory_xact_lock(hashtextextended('territorial-legends:correction', 0));

  select coalesce(array_agg(distinct affected.user_id), '{}'::text[])
    into v_affected_users
    from (
      select h.user_id
        from public.territorial_legend_hold_periods h
       where h.id = any(v_hold_period_ids)
      union
      select p.user_id
        from public.territorial_legend_award_proofs p
       where p.proof_id = any(v_proof_ids)
          or p.hold_period_id = any(v_hold_period_ids)
    ) affected;

  update public.territorial_legend_hold_periods
     set ended_on = coalesce(ended_on, last_verified_on),
         validity_status = 'invalidated',
         updated_at = clock_timestamp()
   where id = any(v_hold_period_ids)
     and validity_status <> 'invalidated';
  get diagnostics v_hold_count = row_count;

  update public.territorial_legend_award_proofs
     set validity_status = 'invalidated',
         valid_until = case
           when p_invalidated_on > valid_from then p_invalidated_on - 1
           else null
         end,
         updated_at = clock_timestamp()
   where validity_status = 'active'
     and (
       proof_id = any(v_proof_ids)
       or hold_period_id = any(v_hold_period_ids)
     );
  get diagnostics v_proof_count = row_count;

  return jsonb_build_object(
    'status', 'applied',
    'invalidatedHoldPeriods', v_hold_count,
    'invalidatedAwardProofs', v_proof_count,
    'affectedUserIds', to_jsonb(v_affected_users)
  );
end;
$$;

revoke all on function public.invalidate_territorial_legend_history(bigint[], text[], date) from public, anon, authenticated;
grant execute on function public.invalidate_territorial_legend_history(bigint[], text[], date) to service_role;
